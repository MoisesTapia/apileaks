def _build_input_schema(descriptor: OwaspModuleDescriptor) -> dict[str, Any]:
    """Build a JSON Schema for an OWASP module tool's input parameters.

    Combines the :data:`_BASE_PROPERTIES` common to all OWASP module tools
    with any module-specific properties from :data:`_MODULE_EXTRA_PROPERTIES`.

    Args:
        descriptor: The module's :class:`~cli.owasp_descriptors.OwaspModuleDescriptor`.

    Returns:
        A JSON Schema dict (draft-07 compatible).
    """
    all_properties = dict(_BASE_PROPERTIES)
    extra = _MODULE_EXTRA_PROPERTIES.get(descriptor.key, {})
    all_properties.update(extra)

    return {
        "$schema": "http://json-schema.org/draft-07/schema#",
        "type": "object",
        "required": ["target"],
        "additionalProperties": False,
        "properties": all_properties,
    }


