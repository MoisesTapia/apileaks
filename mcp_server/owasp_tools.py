def _build_owasp_module_config(
    params: dict[str, Any],
    descriptor: OwaspModuleDescriptor,
):
    """Build an :class:`~core.config.APILeakConfig` for a single OWASP module.

    Uses the same :func:`~cli.config_builders.create_enhanced_config` path the
    CLI uses, then overrides ``enabled_modules`` to contain only the target
    module key so the engine runs exclusively that module's detection logic.

    Module-specific options (e.g. BOLA flags, SSRF knobs) are applied via
    ``descriptor.apply_options`` — the exact same callable the CLI subcommand
    uses — so behaviour is byte-identical.

    Args:
        params: Validated MCP input parameters (already schema-validated by the
                registry before this function is called).
        descriptor: The module's descriptor carrying ``key``, ``config_field``,
                    and ``apply_options``.

    Returns:
        A tuple ``(cfg, config_manager)`` — the ready-to-use config and its
        manager (retained so validation can be re-run if needed).
    """
    target = params["target"]

    # Build the base config dict using the same helper as the CLI.
    config_dict = create_enhanced_config(
        target_url=target,
        wordlist_path=None,
        scan_type="full",
        user_agent_config=None,
        output_filename=None,
        advanced_config={
            "detect_framework": False,
            "fuzz_versions": False,
            "framework_confidence": 0.6,
            "enable_payload_encoding": False,
            "enable_waf_evasion": False,
            "enable_subdomain_discovery": False,
            "enable_cors_analysis": False,
        },
        status_code_filter=None,
        ci_mode=False,
        fail_on="high",
        safe_mode=params.get("safe_mode", False),
    )

    # --- Discovery / budget controls (mirrors _apply_transversal_overrides) -
    config_dict["fuzzing"]["max_depth"] = resolve_max_depth(params.get("depth"))
    if params.get("recursive") is not None:
        config_dict["fuzzing"]["recursive"] = params["recursive"]
    if params.get("max_requests") is not None:
        config_dict["fuzzing"]["max_requests"] = params["max_requests"]
    if params.get("concurrency") is not None:
        config_dict["fuzzing"]["concurrency"] = params["concurrency"]
    if params.get("timeout") is not None:
        config_dict["target"]["timeout"] = params["timeout"]
    if params.get("retries") is not None:
        config_dict["fuzzing"]["retries"] = params["retries"]
    if params.get("depth") == 0:
        config_dict["fuzzing"]["recursive"] = False

    # --- Rate limit / proxy -------------------------------------------------
    if params.get("rate_limit"):
        config_dict.setdefault("rate_limiting", {})
        config_dict["rate_limiting"]["requests_per_second"] = params["rate_limit"]
    if params.get("proxy"):
        config_dict["proxy"] = params["proxy"]

    # Load + validate
    config_manager = ConfigurationManager()
    cfg = config_manager.load_config_from_dict(config_dict)

    # --- Enable ONLY this OWASP module --------------------------------------
    cfg.owasp_testing.enabled_modules = [descriptor.key]

    # --- Safe mode (post-load) ----------------------------------------------
    if params.get("safe_mode") and hasattr(cfg, "safe_mode"):
        cfg.safe_mode = True

    # --- Multi-user auth contexts -------------------------------------------
    auth_context_values = params.get("auth_context") or []
    if auth_context_values:
        try:
            parsed_contexts = parse_auth_context_option(auth_context_values)
        except Exception as exc:
            raise MCPToolError(
                f"Invalid auth_context values: {exc}",
                error_code="INVALID_PARAMS",
            ) from exc
        if parsed_contexts and hasattr(cfg, "authentication"):
            cfg.authentication.contexts.extend(parsed_contexts)

    # --- Module-specific options -------------------------------------------
    # ``apply_options`` is the same callable the CLI subcommand uses to mutate
    # the module's config dataclass from collected option values (dest names →
    # values).  We pass the MCP ``params`` dict directly since the JSON Schema
    # property names were chosen to match Click dest names exactly.
    if descriptor.apply_options is not None:
        module_cfg = getattr(cfg.owasp_testing, descriptor.config_field)
        descriptor.apply_options(module_cfg, params)

    return cfg, config_manager


