"""
mcp_server.owasp_tools — MCP tool specs for individual OWASP modules.

Implements Task 2.2: register one :class:`~mcp_server.schemas.MCPToolSpec`
per OWASP module, auto-generated by iterating over
:data:`~cli.owasp_descriptors.OWASP_MODULE_DESCRIPTORS` — the single source
of truth for the module list — so that adding or removing a module from the
descriptors automatically updates the MCP tool set without any manual wiring
here.

Tool names follow the pattern ``apileak.owasp.<key>``
(e.g. ``apileak.owasp.bola``, ``apileak.owasp.auth``, …).

Each handler:
- Runs the scan engine with **only** the target module enabled (plus
  discovery), reusing the same :class:`~core.engine.APILeakCore` path the
  CLI uses.
- Applies module-specific options via ``descriptor.apply_options`` — the same
  callable the CLI subcommands use — so option semantics are byte-identical.
- Returns :class:`~mcp_server.schemas.MCPToolResult` with structured findings
  (Requirement 1.4).
- Sets ``untrusted_content=True`` because findings contain verbatim target
  response data (Requirement 4.8 / OWASP MCP06).

**No shell interpolation** — all parameters are passed as data objects, never
via string concatenation or ``shell=True`` (Requirement 4.6 / OWASP MCP05).

Note: ``is_destructive=False`` for all tools in this task.  The destructive
confirmation gate (marking ``bola`` / ``function_auth`` as destructive and
wiring :class:`~mcp_server.confirmation_gate.DestructiveConfirmationGate`)
arrives in Task 6.1.

Requirements: 1.2, 1.4
"""

